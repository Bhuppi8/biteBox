import React, { useState, useEffect } from "react";
// 1. Service to fetch data from Optimizely
const fetchOptimizelyContent = async (contentId) => {
  const BASE_URL =
    "https://your-optimizely-site.com/api/episerver/v2.0/content";
  try {
    const response = await fetch(`${BASE_URL}/${contentId}`, {
      headers: {
        Accept: "application/json",
        // 'Authorization': 'Bearer ' + token // If using OAuth
      },
    });
    return await response.json();
  } catch (error) {
    console.error("CMS Fetch Error:", error);
    return null;
  }
};
// 2. React Component using the data
const PageRenderer = ({ pageId }) => {
  const [content, setContent] = useState(null);
  useEffect(() => {
    fetchOptimizelyContent(pageId).then((data) => setContent(data));
  }, [pageId]);
  if (!content) return <div>Loading...</div>;
  return (
    <div className="page-wrapper">
      {/* Mapping Optimizely properties to UI */}
      <h1>{content.name}</h1>
      <div dangerouslySetInnerHTML={{ __html: content.mainBody?.value }} />
      {/* Example of rendering dynamic blocks/areas */}
      {content.mainContentArea?.value?.map((block) => (
        <div key={block.contentLink.id}>
          {/* Logic to render specific block types */}
          Generated by Clause AI Page 3 of 8 Render Block: {block.displayOption}
        </div>
      ))}
    </div>
  );
};
export default PageRenderer;
